  await expect(page.getByText('控制条件可比较 · FULL',{exact:true})).toBeVisible()
  expect((await p()).comparison).toBe(ids.comparison)
  await page.getByRole('button',{name:'03 Evaluate 运行与找问题',exact:true}).click()
  await page.getByRole('combobox',{name:/查看哪次检索/}).selectOption('BASELINE')
