  await page.getByLabel('API Key',{exact:true}).fill(key)
  await page.getByRole('button',{name:'保存模型会话',exact:true}).click()
  await expect(page.getByText('凭据已加载到当前会话',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'测试连接',exact:true}).click()
  await expect(page.getByText('✓ 模型连接成功',{exact:true})).toBeVisible()
  await page.getByLabel('实验路径',{exact:false}).selectOption('RETRIEVAL')
  await page.getByRole('button',{name:'02 Define 定义目标与测试',exact:true}).click()
  await page.getByRole('button',{name:'载入 Demo 知识与 8 道题',exact:true}).click()
  await page.getByRole('button',{name:'保存知识版本',exact:true}).click()
  await expect(page.getByText('已保存 8 份文档 · Version 1。历史版本保留。',{exact:true})).toBeVisible()
  await page.screenshot({path:evidence+'/rag-knowledge-1440.png',fullPage:true})
  await page.getByRole('button',{name:'建立冻结索引',exact:true}).click()
  await expect(page.getByText('索引 READY · 8 个 Chunk · 知识 Version 1',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'保存检索测试，准备 Baseline →',exact:true}).click()
  await page.getByLabel('返回候选数量 Top K',{exact:true}).fill('1')
  await page.getByLabel('同时验证最终回答（会调用 Agent 和 Judge）',{exact:true}).check()
  await page.getByRole('button',{name:'开始检索 Baseline',exact:true}).click()
  await expect(page.locator('.rag-case')).toHaveCount(8)
  const p=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('echomind.retrieval.v1')))
  let ids=await p()
  const a=await (await request.get('/api/experiments/retrieval-runs/'+ids.baseline)).json()
  expect(a.run.status).toBe('COMPLETE')
  expect(a.run.case_results).toHaveLength(8)
  const bad=a.run.case_results.find(c=>c.metrics.relevant_rank!==1)
  expect(bad).toBeTruthy()
  await page.screenshot({path:evidence+'/rag-baseline-1440.png',fullPage:true})
  await page.getByTestId('retrieval-case-'+bad.case_id).getByRole('button',{name:'基于这题选择修改 →',exact:true}).click()
  await page.getByRole('button',{name:'预览模型查询改写',exact:true}).click()
  await expect(page.getByText('模型预览 · 尚未应用',{exact:true})).toBeVisible()
  expect((await p()).change).toBeUndefined()
  await page.getByLabel('选择理由与可能副作用',{exact:true}).fill('口语化输入没有命中正确知识，尝试改写为知识搜索词。风险是模型可能改变原意。')
  await page.getByLabel('我确认这是我的产品判断，只修改上述一个变量',{exact:true}).check()
  await page.getByRole('button',{name:'确认并记录修改',exact:true}).click()
  await page.getByRole('button',{name:'Apply · 应用检索配置',exact:true}).click()
  await expect(page.getByRole('button',{name:'运行检索 Retest →',exact:true})).toBeEnabled()
  await page.screenshot({path:evidence+'/rag-change-1440.png',fullPage:true})
  await page.getByRole('button',{name:'运行检索 Retest →',exact:true}).click()
  await expect(page.locator('.rag-case')).toHaveCount(8)
  await page.getByRole('button',{name:'比较检索前后变化 →',exact:true}).click()
