  const c=await (await request.get('/api/experiments/retrieval-comparisons/'+ids.comparison)).json()
  const change=await (await request.get('/api/experiments/retrieval-changes/'+ids.change)).json()
  expect(c.comparable).toBe(true);expect(c.attributable).toBe(false);expect(c.single_recorded_change).toBe(true)
  expect(c.case_pairs.some(c=>c.transition==='RETRIEVAL_IMPROVED')).toBe(true)
  expect(c.case_pairs.some(c=>c.answer_transition==='FAIL→PASS')).toBe(true)
  expect(a.run.controls).toEqual(b.run.controls)
  expect(change.declared_diff).toEqual(change.observed_diff)
  expect(b.run.metrics.hit_at_1).toBeGreaterThan(a.run.metrics.hit_at_1)
  expect(b.run.metrics.mrr).toBeGreaterThan(a.run.metrics.mrr)
